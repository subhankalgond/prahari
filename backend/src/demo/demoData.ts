export function demoScanResult(
  scanId: string,
  cropName: string,
  condition: string,
  confidence: number,
  severity: Severity,
  isHealthy: boolean,
  symptoms: string[],
  causes: string[],
  actions: string[],
  prevention: string[],
  createdAt: string,
): ScanResult {
  return {
    id: demoId('res'),
    scanId,
    crop: cropName,
    condition,
    isHealthy,
    confidence,
    severity: isHealthy ? null : severity,
    status: isHealthy ? 'HEALTHY' : confidence < 60 ? 'LOW_CONFIDENCE' : 'NEEDS_ATTENTION',
    symptoms,
    causes,
    actions,
    prevention,
    expertHelp:
      'If symptoms continue or the result is uncertain, consult a qualified agricultural expert or your local Krishi Vigyan Kendra before treatment.',
    provider: 'demo',
    isDemo: true,
    createdAt,
  };
}

